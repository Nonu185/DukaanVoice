/**
 * Resolves nested translation key like 'dashboard.todayRevenue' for the active language,
 * replacing {placeholder} variables cleanly.
 */
export function translate(language, key, vars = {}) {
  const langDict = translations[language] || translations.en;
  const parts = key.split('.');
  let current = langDict;

  for (const part of parts) {
    if (current && typeof current === 'object' && part in current) {
      current = current[part];
    } else {
      // Fallback to English dictionary if key missing
      current = translations.en;
      for (const p of parts) {
        if (current && typeof current === 'object' && p in current) {
          current = current[p];
        } else {
          return key;
        }
      }
      break;
    }
  }

  if (typeof current !== 'string') return key;

  return current.replace(/\{(\w+)\}/g, (_, k) =>
    vars[k] !== undefined ? String(vars[k]) : `{${k}}`
  );
}

